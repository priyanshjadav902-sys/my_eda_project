IQR = Q3 - Q1
clean = df[(df['Profit'] >= Q1 - 1.5*IQR) & (df['Profit'] <= Q3 + 1.5*IQR)]

print(f"\nMean   WITHOUT outliers: {clean['Profit'].mean():.2f}")
