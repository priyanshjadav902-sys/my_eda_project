"""#• Handle missing values using:
* Mean / Median / Mode
"""

# Continuous columns → Median (bcz of outliers)
median_cols = ['price', 'final_price', 'discount_percent', 'rating']
for col in median_cols:
    median_val = df[col].median()
    df[col].fillna(median_val, inplace=True)
    print(f"{col} → filled with Median: {median_val}")

# Discrete columns → Mean
mean_cols = ['stock', 'Profit', 'Loss']
for col in mean_cols:
    mean_val = round(df[col].mean())
    df[col].fillna(mean_val, inplace=True)
    print(f"{col} → filled with Mean: {mean_val}")

# Categorical columns → Mode
cat_cols = ['category', 'brand']
for col in cat_cols:
    mode_val = df[col].mode()[0]
    df[col].fillna(mode_val, inplace=True)
    print(f"{col} → filled with Mode: {mode_val}")

# Verify
print("\n=== AFTER FILLING - MISSING VALUES ===")
print(df.isnull().sum())

